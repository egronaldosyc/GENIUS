for key, who, find, ss, es, mx in SPEC:
    cand = [r for r in rows if r['who'].startswith(who) and norm(find) in norm(r['text'])]
    if not cand: print('MISS', key); continue
    r = cand[0]; words = [w for s in TR[r['file']] for w in s['words']]
    nw = [norm(w[2]) for w in words]
    def idx(sub, default):
        if not sub: return default
        toks = norm(sub).split()
        for i in range(len(nw)):
            if nw[i].startswith(toks[0][:max(3, len(toks[0]) - 1)]) and all(i + j < len(nw) and nw[i + j].startswith(t[:max(2, len(t) - 2)]) for j, t in enumerate(toks[:2])): return i
